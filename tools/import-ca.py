"""Import Cloudflare issuer roots from the Defold SDK's Mozilla CA bundle."""

import re
import sys
from pathlib import Path
from zipfile import ZipFile

with ZipFile(sys.argv[1]) as archive:
    source = archive.read("builtins/ca-certificates/cacert.pem").decode("utf-8")

roots = re.findall(
    r"(?m)^((?:GTS Root|ISRG Root|SSL\.com)[^\n]*)\n=+\n(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)",
    source,
    re.S,
)
assert len(roots) >= 6, "Expected Google Trust Services and ISRG issuer roots"
destination = Path(__file__).resolve().parents[1] / "scoreosis/cacert.pem"
destination.write_text(
    "# Generated by tools/import-ca.py from Defold's Mozilla CA bundle.\n"
    "# Google Trust Services, Let's Encrypt, and SSL.com roots for Cloudflare APIs.\n\n"
    + "\n\n".join(name + "\n" + block for name, block in roots)
    + "\n",
    encoding="ascii",
)
print(f"Imported {len(roots)} public CA roots")
